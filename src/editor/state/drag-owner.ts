/**
 * Who owns a drag that just started on the canvas?
 *
 * `pressed` — the layer the pointer went down on (WYSIWYG).
 * `selection` — the layer highlighted in the layer panel takes the gesture over.
 *
 * The canvas used to answer "selection" far too often: every drag that started
 * inside the selected layer was handed over, judged by `Shape.intersects` (which
 * is alpha accurate). On paper that only covered the "my picture is completely
 * hidden behind an opaque layer" case. On screen, right after the auto-layout
 * selects the hero, it meant that pressing the product-code label, a packaging
 * box or the backdrop moved the HERO — the layer under the finger stayed put,
 * which the user reports as "画布很难拖动". A gesture that moves something other
 * than what you pressed is worse than a gesture that does nothing.
 *
 * Two exceptions survive, and both are cases where pressing cannot mean what it
 * hit:
 *
 * 1. the **backdrop plate** is scenery generated by the planner. Pressing it
 *    inside the selection's box means "move the subject".
 * 2. **Alt** while pressing anything is an explicit "the selection, not what I
 *    hit". That is the escape hatch for a layer that is completely covered by an
 *    opaque one, where no pixel test can ever reach it.
 *
 * And one that is deliberately conditional: a layer the user selected **by hand**
 * takes the gesture over — see {@link DragOwnerInput.selectionIsExplicit}. A cut-out
 * is mostly transparent margin, so its own box covers the layer underneath; without
 * this, a picture that is partly covered could only be moved by its few exposed
 * pixels. The condition is what keeps the 10.3.4 complaint from coming back: the
 * hero that the planner selects *by itself* gets no such priority, so the first
 * gesture after composing still moves what you pressed.
 *
 * The containment test is a **bounding box**, not alpha, on purpose: measuring
 * the alpha would need `Shape.intersects()`, which repaints the whole shape into
 * a throwaway hit canvas and reads a pixel back from the GPU — inside a
 * `dragstart`, i.e. on the first frame of the gesture. The box is a cached
 * rect and cannot be felt.
 */
export type DragOwner = 'pressed' | 'selection';

/** Stage-space box, as returned by `Konva.Node.getClientRect()`. */
export interface DragBox {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface DragPoint {
  x: number;
  y: number;
}

export interface DragOwnerInput {
  /** Layer the press landed on (`null` = the empty stage). */
  pressedId: string | null;
  /** The pressed layer is the planner's backdrop plate (scenery, not a subject). */
  pressedIsBackdrop: boolean;
  /** Layer currently highlighted in the panel. */
  selectedId: string | null;
  /**
   * The pointer is inside the selected layer's bounding box.
   *
   * Callers pass `false` when the selection is off-canvas or unresolvable — "we
   * could not check" must never read as "it is there".
   */
  pointerInsideSelection: boolean;
  /** Alt / ⌥ held during the press. */
  forceSelection: boolean;
  /**
   * The current selection came from the user (a click on the canvas, a row in the
   * layer panel, picking a layer in any other explicit way) rather than from an
   * automatic step such as the planner selecting the hero after composing.
   *
   * Only an explicit selection can claim a gesture that landed on a different
   * layer: "I picked this one, so drag this one".
   */
  selectionIsExplicit: boolean;
}

export function decideDragOwner(input: DragOwnerInput): DragOwner {
  const {
    pressedId,
    pressedIsBackdrop,
    selectedId,
    pointerInsideSelection,
    forceSelection,
    selectionIsExplicit,
  } = input;
  // Nothing selected, or the press landed on the selection itself: the pressed
  // layer is the answer either way.
  if (!pressedId || !selectedId || pressedId === selectedId) return 'pressed';
  // Out of the selection's box: the selection cannot claim a gesture that far
  // away. This is what keeps the plate draggable on a hero-free part of the
  // canvas, and what keeps a picture's own margin usable.
  if (!pointerInsideSelection) return 'pressed';
  if (forceSelection || pressedIsBackdrop || selectionIsExplicit) return 'selection';
  return 'pressed';
}

/** Inclusive point-in-box test in the same coordinate space (stage pixels). */
export function pointInsideBox(box: DragBox, point: DragPoint): boolean {
  return (
    point.x >= box.x &&
    point.x <= box.x + box.width &&
    point.y >= box.y &&
    point.y <= box.y + box.height
  );
}
